CREATE TABLE [dbo].[BROADCASTS] (
    [BROADCAST_ID]     INT            IDENTITY (1, 1) NOT NULL,
    [CLIENT_ID]        INT            NOT NULL,
    [TITLE]            NVARCHAR (500) NOT NULL,
    [MESSAGE]          NVARCHAR (MAX) NOT NULL,
    [CHANNEL]          NVARCHAR (20)  NOT NULL,
    [TARGET_FILTER]    NVARCHAR (MAX) NULL,
    [SCHEDULED_AT]     DATETIME2 (7)  NULL,
    [SENT_AT]          DATETIME2 (7)  NULL,
    [CREATED_BY]       INT            NULL,
    [RECIPIENT_COUNT]  INT            NOT NULL DEFAULT ((0)),
    [DELIVERED_COUNT]  INT            NOT NULL DEFAULT ((0)),
    [FAILED_COUNT]     INT            NOT NULL DEFAULT ((0)),
    [IS_DELETED]       BIT            NOT NULL DEFAULT ((0)),
    [CREATED_DATE]     DATETIME2 (7)  DEFAULT (getdate()) NOT NULL,
    [MODIFIED_DATE]    DATETIME2 (7)  NULL,
    [MODIFIED_BY]      INT            NULL,
    PRIMARY KEY CLUSTERED ([BROADCAST_ID] ASC),
    CONSTRAINT [FK_BROADCASTS_CLIENTS] FOREIGN KEY ([CLIENT_ID]) REFERENCES [dbo].[CLIENTS] ([CLIENT_ID])
);
